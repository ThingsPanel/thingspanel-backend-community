#!/usr/bin/env python3
"""Generate sql/mysql/014_platform_seed.sql: the rows the PostgreSQL migrations insert, for MySQL.

The root migrations are applied to a scratch PostgreSQL first (scripts/dev-databases.sh does that); the rows
they left behind are exported, so nothing is copied by hand. Every row is a single-row INSERT with a no-op
ON DUPLICATE KEY UPDATE, so re-running never overwrites what an operator changed since.

Usage: pg2mysql_seed.py "<psql command prefix>" > sql/mysql/014_platform_seed.sql
"""
import json
import shlex
import subprocess
import sys
from datetime import datetime, timezone

# table -> primary key column(s) used for the no-op update
TABLES = {
    'sys_function': ['id'], 'sys_dict': ['id'], 'sys_dict_language': ['id'], 'sys_ui_elements': ['id'],
    'data_policy': ['id'], 'logo': ['id'], 'notification_services_config': ['id'], 'service_plugins': ['id'],
    'users': ['id'], 'boards': ['id'],
}
# casbin_rule is created by the gorm adapter on PostgreSQL and has no rows after the migrations except the ones
# sql/25.sql registers; MySQL has the table from migration 005, so the same rows are listed here.
CASBIN = [
    ('g2', 'api/v1/notification-default-policy', 'api/v1/notification-default-policy', ''),
    ('p', 'SYS_ADMIN', 'api/v1/notification-default-policy', 'allow'),
    ('p', 'TENANT_ADMIN', 'api/v1/notification-default-policy', 'allow'),
]


def psql(prefix, sql):
    return subprocess.run(shlex.split(prefix) + ['-At', '-c', sql], capture_output=True, text=True, check=True).stdout


def quote(v, kind):
    if v is None:
        return 'NULL'
    if kind in ('json', 'jsonb'):
        v = json.dumps(v, ensure_ascii=False, separators=(',', ':'))
    elif isinstance(v, bool):
        return '1' if v else '0'
    elif isinstance(v, (int, float)):
        return repr(v)
    elif kind.startswith('timestamp'):
        text = v.replace('Z', '+00:00')
        dt = datetime.fromisoformat(text)
        if dt.tzinfo:
            dt = dt.astimezone(timezone.utc).replace(tzinfo=None)
        v = dt.strftime('%Y-%m-%d %H:%M:%S.%f')
    s = str(v).replace('\\', '\\\\').replace("'", "''")
    return "'" + s + "'"


def main():
    prefix = sys.argv[1]
    out = ['-- Generated by scripts/pg2mysql_seed.py from the rows the PostgreSQL migrations insert. Do not edit by hand.']
    for table, pk in TABLES.items():
        kinds = {}
        for line in psql(prefix, f"select column_name||'|'||data_type from information_schema.columns where table_schema='public' and table_name='{table}'").splitlines():
            name, kind = line.split('|')
            kinds[name] = kind
        raw = psql(prefix, f"select coalesce(json_agg(t order by {', '.join(pk)}), '[]'::json) from {table} t")
        for row in json.loads(raw):
            cols = list(row.keys())
            values = ', '.join(quote(row[c], kinds[c]) for c in cols)
            noop = f'`{pk[0]}` = `{pk[0]}`'
            out.append(f"INSERT INTO `{table}` ({', '.join('`' + c + '`' for c in cols)}) VALUES ({values}) ON DUPLICATE KEY UPDATE {noop}")
    for ptype, v0, v1, v2 in CASBIN:
        out.append(f"INSERT INTO `casbin_rule` (`ptype`, `v0`, `v1`, `v2`) SELECT '{ptype}', '{v0}', '{v1}', '{v2}' FROM DUAL "
                   f"WHERE NOT EXISTS (SELECT 1 FROM `casbin_rule` WHERE `ptype` = '{ptype}' AND `v0` = '{v0}' AND `v1` = '{v1}' AND `v2` = '{v2}')")
    sys.stdout.write('\n-- @@\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
