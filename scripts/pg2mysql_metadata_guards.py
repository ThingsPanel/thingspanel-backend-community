#!/usr/bin/env python3
"""Generate the MySQL triggers that stand in for the device_metadata PostgreSQL trigger functions.

Usage: pg2mysql_metadata_guards.py "<psql prefix for the device_metadata database>" > encore-api/devicemetadata/mysqlschema/002_guards.sql

PostgreSQL enforces these invariants with plpgsql triggers; MySQL needs its own triggers (error 3819, the check
violation number, carries the same meaning as PostgreSQL's SQLSTATE 23514). Generated here: tenant_id immutability
(one trigger per table that has it in PostgreSQL) and "updated_at moves when a row really changes". The simple
hand-ported guards are templates below. NOT ported (listed in ../README-mysql.md): the gateway tree validator, the
deferred gateway state check, and the template model selection resolver.
"""
import re
import shlex
import subprocess
import sys


def psql(prefix, sql):
    return subprocess.run(shlex.split(prefix) + ['-At', '-F', '|', '-c', sql], capture_output=True, text=True, check=True).stdout


def signal(message):
    return f"SIGNAL SQLSTATE '23000' SET MYSQL_ERRNO = 3819, MESSAGE_TEXT = '{message}'"


def raise_exception(message):
    """PostgreSQL's plain RAISE EXCEPTION (SQLSTATE P0001) is SIGNAL SQLSTATE '45000' (error 1644)."""
    return f"SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = '{message}'"


def trigger(name, table, event, body):
    return [f'DROP TRIGGER IF EXISTS `{name}`',
            f'CREATE TRIGGER `{name}` BEFORE {event} ON `{table}` FOR EACH ROW\nBEGIN\n{body}\nEND']


def main():
    prefix = sys.argv[1]
    out = ['-- Generated by scripts/pg2mysql_metadata_guards.py. Do not edit by hand.']
    # tenant_id immutability
    tables = [l.split('|')[0] for l in psql(prefix, "select tgrelid::regclass::text from pg_trigger where not tgisinternal and tgfoid::regproc::text='reject_tenant_id_reassignment' order by 1").splitlines()]
    for table in tables:
        out += trigger(f'trg_{table}_tenant_id_immutable', table, 'UPDATE',
                       f"    IF NOT (NEW.`tenant_id` <=> OLD.`tenant_id`) THEN\n        {signal('tenant_id is immutable')};\n    END IF;")
    # updated_at moves when a row really changes
    stamp = {'devices': True, 'device_access_bindings': True, 'device_credentials': True, 'gateway_memberships': True, 'device_runtime_outbox': False}
    for table, explicit in stamp.items():
        cols = [l.split('|') for l in psql(prefix, f"select column_name, is_generated from information_schema.columns where table_schema='public' and table_name='{table}' order by ordinal_position").splitlines()]
        compared = [c for c, generated in cols if c != 'updated_at' and generated == 'NEVER']
        same = ' AND '.join(f'NEW.`{c}` <=> OLD.`{c}`' for c in compared)
        condition = f'NOT ({same})' + (' OR NOT (NEW.`updated_at` <=> OLD.`updated_at`)' if explicit else '')
        out += trigger(f'trg_{table}_updated_at', table, 'UPDATE',
                       f"    IF {condition} THEN\n        SET NEW.`updated_at` = NOW(6);\n    END IF;")
    # hand-ported guards
    out += trigger('trg_snap_no_update', 'thing_model_snapshots', 'UPDATE', f"    {raise_exception('thing_model_snapshots is immutable')};")
    out += trigger('trg_snap_no_delete', 'thing_model_snapshots', 'DELETE', f"    {raise_exception('thing_model_snapshots is immutable')};")
    out += trigger('trg_device_access_bindings_generation', 'device_access_bindings', 'UPDATE',
                   "    IF NEW.`configuration_generation` < OLD.`configuration_generation` THEN\n"
                   f"        {signal('device access binding generation cannot decrease')};\n    END IF;\n"
                   "    IF (NOT (NEW.`template_id` <=> OLD.`template_id`) OR NOT (NEW.`direct_access` <=> OLD.`direct_access`)\n"
                   "        OR NOT (NEW.`device_parameters` <=> OLD.`device_parameters`))\n"
                   "       AND NEW.`configuration_generation` <= OLD.`configuration_generation` THEN\n"
                   f"        {signal('device access configuration changes require a newer generation')};\n    END IF;")
    out += trigger('trg_device_access_bindings_identity_immutable', 'device_access_bindings', 'UPDATE',
                   "    IF NOT (NEW.`tenant_id` <=> OLD.`tenant_id`) OR NOT (NEW.`device_id` <=> OLD.`device_id`) THEN\n"
                   f"        {signal('device access binding identity is immutable')};\n    END IF;")
    out += trigger('trg_device_credentials_identity_immutable', 'device_credentials', 'UPDATE',
                   "    IF NOT (NEW.`id` <=> OLD.`id`) OR NOT (NEW.`tenant_id` <=> OLD.`tenant_id`) OR NOT (NEW.`device_id` <=> OLD.`device_id`)\n"
                   "       OR NOT (NEW.`template_id` <=> OLD.`template_id`) OR NOT (NEW.`purpose` <=> OLD.`purpose`) THEN\n"
                   f"        {signal('device credential identity is immutable')};\n    END IF;")
    out += trigger('trg_device_credentials_revocation_immutable', 'device_credentials', 'UPDATE',
                   "    IF OLD.`status` = 'revoked' AND (NOT (NEW.`status` <=> 'revoked') OR NOT (NEW.`revoked_at` <=> OLD.`revoked_at`)\n"
                   "       OR NOT (NEW.`revoked_by` <=> OLD.`revoked_by`) OR NOT (NEW.`revocation_reason` <=> OLD.`revocation_reason`)) THEN\n"
                   f"        {signal('device credential revocation is immutable')};\n    END IF;")
    out += trigger('trg_gateway_memberships_identity_immutable', 'gateway_memberships', 'UPDATE',
                   "    IF NOT (NEW.`tenant_id` <=> OLD.`tenant_id`) OR NOT (NEW.`child_device_id` <=> OLD.`child_device_id`) THEN\n"
                   f"        {signal('gateway membership identity is immutable')};\n    END IF;")
    out += trigger('trg_metadata_operations_terminal_state', 'metadata_operations', 'UPDATE',
                   "    IF OLD.`state` IN ('succeeded', 'failed', 'cancelled') AND NOT (NEW.`state` <=> OLD.`state`) THEN\n"
                   f"        {signal('metadata operation terminal state is immutable')};\n    END IF;")
    out += trigger('trg_metadata_operation_items_terminal_state', 'metadata_operation_items', 'UPDATE',
                   "    IF OLD.`state` IN ('succeeded', 'failed', 'skipped') AND NOT (NEW.`state` <=> OLD.`state`) THEN\n"
                   f"        {signal('metadata operation item terminal state is immutable')};\n    END IF;")
    cols = ['id', 'tenant_id', 'created_at', 'created_by', 'operation_id', 'purpose', 'file_owner', 'file_object_id', 'file_name',
            'content_type', 'size_bytes', 'checksum']
    out += trigger('trg_metadata_artifacts_z_content_immutable', 'metadata_artifacts', 'UPDATE',
                   '    IF ' + ' OR '.join(f'NOT (NEW.`{c}` <=> OLD.`{c}`)' for c in cols) + ' THEN\n'
                   f"        {signal('metadata artifact content is immutable')};\n    END IF;\n"
                   "    IF OLD.`state` IN ('expired', 'deleted') AND NEW.`state` IN ('ready', 'staged') THEN\n"
                   f"        {signal('metadata artifact lifecycle cannot move backward')};\n    END IF;")
    sys.stdout.write('\n-- @@\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
