package notification

import (
	"context"
	"time"

	"encore.app/l3-core/notification/contract"
)

// These are the narrow application boundaries frozen for follow-on tasks.
// They contain no Encore, SQL, or plugin HTTP client types. Implementations
// live in this notification service and are introduced by their owning tasks.

type InstanceRepository interface {
	GetInstance(ctx context.Context, tenantID, instanceID string) (contract.InstanceView, error)
}

type GroupResolver interface {
	ResolvePublished(ctx context.Context, tenantID, groupID string, revision int64) (contract.GroupView, error)
}

type SourceProjectionStore interface {
	// The source principal must be bound to the deployment and tenant before
	// this method is called. A source tuple has one permanent target group and
	// one immutable record per published revision. Replays return the original
	// record without lowering the latest revision; a new historical revision may
	// be backfilled. Enforce a 128-record cap atomically and return all records
	// sorted by groupRevision from ListGroupProjections.
	RegisterGroupProjection(ctx context.Context, principal SourceProjectionPrincipal, request contract.SourceGroupProjectionRequest) (contract.SourceGroupProjection, error)
	ListGroupProjections(ctx context.Context, tenantID, groupID string) ([]contract.SourceGroupProjection, error)
}

type SubmissionStore interface {
	// Replays with identical tenant/key/digest return stable business IDs; the
	// HTTP requestId is generated by the current request boundary.
	AcceptSubmission(ctx context.Context, tenantID, idempotencyKey, intentDigest string, request contract.NotificationSubmit) (contract.AcceptedData, error)
	GetNotification(ctx context.Context, tenantID, notificationID string) (contract.NotificationView, error)
}

type DeliveryClaim struct {
	TenantID   string
	DeliveryID string
	AttemptID  string
	LeaseToken string
	ExpiresAt  time.Time
	Request    contract.PluginSendRequestV1
}

type DeliveryFinish struct {
	TenantID   string
	DeliveryID string
	AttemptID  string
	LeaseToken string
	Result     contract.PluginSendResultV1
	FinishedAt time.Time
}

type DeliveryStore interface {
	// A claim carries a fencing token. Expired in-flight attempts recover to
	// unknown unless there is evidence that no provider side effect occurred.
	ClaimDeliveries(ctx context.Context, limit int, leaseFor time.Duration) ([]DeliveryClaim, error)
	FinishDelivery(ctx context.Context, result DeliveryFinish) error
	RecoverExpiredClaims(ctx context.Context, now time.Time) (recovered int, err error)
}

type UserPrincipal struct {
	UserID   string
	TenantID string
	Roles    []string
	Scopes   []string
}

type SourcePrincipal struct {
	DeploymentID string
	TenantIDs    []string
}

type SourceProjectionPrincipal struct {
	DeploymentID string
	TenantIDs    []string
}

type ReceiptPrincipal struct {
	TenantID   string
	InstanceID string
}

type PrincipalVerifier interface {
	VerifyUser(ctx context.Context, bearer string) (UserPrincipal, error)
	VerifySource(ctx context.Context, bearer string) (SourcePrincipal, error)
	VerifySourceProjection(ctx context.Context, bearer string) (SourceProjectionPrincipal, error)
	VerifyReceipt(ctx context.Context, bearer, pathInstanceID string) (ReceiptPrincipal, error)
}

type ReceiptStore interface {
	// The principal's tenant and instance scope come from the credential, never
	// from receipt payload fields. Persist before returning the raw ACK.
	AcceptReceipt(ctx context.Context, principal ReceiptPrincipal, event contract.PluginReceiptV1, eventDigest string) (contract.ReceiptAck, error)
}

type PluginSender interface {
	// Ambiguous network outcomes are represented as outcome=unknown. A plain
	// error is never by itself authorization to retry a provider submission.
	Send(ctx context.Context, request contract.PluginSendRequestV1) (contract.PluginSendResultV1, error)
}

type SourceEventReceiver interface {
	// Durable intake may return ready or blocked; neither state is provider
	// acceptance. Replays retain the original notification identity.
	ReceiveSourceEvent(ctx context.Context, principal SourcePrincipal, idempotencyKey string, event contract.SourceEventV1) (contract.AcceptedData, error)
}
